from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field


class PlanStep(BaseModel):
    """Individual atomic step within an issue resolution plan."""

    step_number: int = Field(..., json_schema_extra={"example": 1})
    title: str = Field(..., json_schema_extra={"example": "Validate authentication token header presence"})
    description: str = Field(..., json_schema_extra={"example": "Inspect request headers and return 401 if Authorization header is missing."})
    target_files: List[str] = Field(default_factory=list, json_schema_extra={"example": ["src/core/auth.py"]})


class StructuredPlan(BaseModel):
    """Structured plan generated by Planner subsystem."""

    objective: str = Field(..., json_schema_extra={"example": "Resolve KeyError by safely extracting bearer token from request headers."})
    affected_files: List[str] = Field(default_factory=list, json_schema_extra={"example": ["src/core/auth.py", "tests/test_auth.py"]})
    steps: List[PlanStep] = Field(default_factory=list)
    risks: List[str] = Field(default_factory=list, json_schema_extra={"example": ["Ensure existing session cookies remain functional."]})
    acceptance_criteria: List[str] = Field(default_factory=list, json_schema_extra={"example": ["Missing auth header returns HTTP 401 instead of 500."]})


class PlanResponse(BaseModel):
    """Response containing generated implementation plan for an issue."""

    run_id: str
    issue_number: int
    plan: StructuredPlan
    created_at: datetime


class PatchItem(BaseModel):
    """Unified code diff generated for a specific file."""

    target_file: str = Field(..., json_schema_extra={"example": "src/core/auth.py"})
    unified_diff: str = Field(..., json_schema_extra={"example": "--- a/src/core/auth.py\n+++ b/src/core/auth.py\n@@ -10,1 +10,3 @@\n- token = headers['Authorization']\n+ token = headers.get('Authorization')\n+ if not token: raise Unauthorized()"})
    explanation: Optional[str] = Field(default="", json_schema_extra={"example": "Replaced dictionary index with .get() to prevent KeyError."})


class PatchResponse(BaseModel):
    """Response containing synthesized code patches."""

    run_id: str
    patches: List[PatchItem]
    summary: str
    created_at: datetime


class ValidationResult(BaseModel):
    """Sandbox execution and testing verification result."""

    run_id: str
    exit_code: int = Field(..., json_schema_extra={"example": 0})
    stdout: str = Field(default="")
    stderr: str = Field(default="")
    duration_ms: int = Field(default=0)
    passed: bool = Field(default=False)
    executed_in_docker: bool = Field(default=False)
    message: str = Field(default="Execution completed.")


class ReviewFinding(BaseModel):
    """Actionable code review finding."""

    severity: str = Field(..., json_schema_extra={"example": "info"})  # info, warning, critical
    file: str = Field(..., json_schema_extra={"example": "src/core/auth.py"})
    line: Optional[int] = Field(default=None, json_schema_extra={"example": 12})
    message: str = Field(..., json_schema_extra={"example": "Good defensive check against missing headers."})
    suggestion: Optional[str] = None


class ReviewResponse(BaseModel):
    """Automated review of proposed code changes."""

    run_id: str
    passed: bool = Field(default=True)
    findings: List[ReviewFinding] = Field(default_factory=list)
    summary: str = Field(default="Code changes adhere to security and styling guidelines.")
    approved_for_pr: bool = Field(default=True)


class RunCreateRequest(BaseModel):
    """Request payload to initiate a new automated issue resolution workflow."""

    repository_full_name: str = Field(..., json_schema_extra={"example": "owner/repo"})
    issue_number: int = Field(..., json_schema_extra={"example": 42})


class RunApprovalRequest(BaseModel):
    """Human decision payload to approve or reject a workflow run for PR creation."""

    action: str = Field(..., json_schema_extra={"example": "approve"})  # "approve" or "reject"
    notes: Optional[str] = Field(default=None, json_schema_extra={"example": "Approved by maintainer."})


class RunStatusResponse(BaseModel):
    """Detailed state of a workflow execution run."""

    id: str
    repository_full_name: str
    issue_number: int
    status: str = Field(..., json_schema_extra={"example": "completed"})  # pending, planner_running, coder_running, tester_running, reviewer_running, awaiting_approval, pr_creating, completed, failed
    current_node: str = Field(..., json_schema_extra={"example": "awaiting_approval"})
    retry_count: int = Field(default=0)
    started_at: datetime
    completed_at: Optional[datetime] = None
    plan: Optional[StructuredPlan] = None
    patches: List[PatchItem] = Field(default_factory=list)
    test_results: Optional[ValidationResult] = None
    review: Optional[ReviewResponse] = None
    pr_url: Optional[str] = None
    pr_number: Optional[int] = None
    error_message: Optional[str] = None


class PullRequestResponse(BaseModel):
    """Pull request creation result."""

    pr_number: int
    pr_url: str
    head_branch: str
    base_branch: str
    status: str
