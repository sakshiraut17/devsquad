"""Patch database model representing immutable code patch revisions."""
import uuid
from datetime import datetime
from typing import TYPE_CHECKING
from sqlalchemy import DateTime, ForeignKey, Integer, JSON, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.db.base import Base, utc_now

if TYPE_CHECKING:
    from app.db.models.run import Run
    from app.db.models.pull_request import PullRequest
    from app.db.models.approval_record import ApprovalRecord
    from app.db.models.security_finding import SecurityFinding
    from app.db.models.security_scan_record import SecurityScanRecord


class Patch(Base):
    """Immutable code patch generated by the Coder agent."""

    __tablename__ = "patches"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )
    run_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("runs.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    revision: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )
    unified_diff: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    target_files: Mapped[list[str]] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )
    summary: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    content_hash: Mapped[str] = mapped_column(
        String(64),
        index=True,
        nullable=False,
    )
    validation_status: Mapped[str] = mapped_column(
        String(50),
        default="pending",
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        nullable=False,
    )

    # Relationships
    run: Mapped["Run"] = relationship(
        "Run",
        back_populates="patches",
    )
    pull_requests: Mapped[list["PullRequest"]] = relationship(
        "PullRequest",
        back_populates="patch",
    )
    approval_records: Mapped[list["ApprovalRecord"]] = relationship(
        "ApprovalRecord",
        back_populates="patch",
    )
    security_findings: Mapped[list["SecurityFinding"]] = relationship(
        "SecurityFinding",
        back_populates="patch",
    )
    security_scans: Mapped[list["SecurityScanRecord"]] = relationship(
        "SecurityScanRecord",
        back_populates="patch",
    )

    __table_args__ = (
        UniqueConstraint(
            "run_id",
            "revision",
            name="uq_run_patch_revision",
        ),
    )
